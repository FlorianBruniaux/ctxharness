// Existing Playwright and system Chrome only. BASE, OUT and PLAYWRIGHT_MODULE are required.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE)
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const base = process.env.BASE
const out = process.env.OUT
assert.ok(base && out)
fs.mkdirSync(out, { recursive: true })
;(async () => {
  const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' })
  try {
    if (process.env.CAPTURE_BEFORE) {
      for (const [theme, width] of [['light',1440],['dark',1440],['light',390]]) {
        const page = await browser.newPage({ viewport:{width,height:900},colorScheme:theme })
        await page.goto(base,{waitUntil:'networkidle'})
        await page.evaluate(() => document.fonts.ready)
        await page.screenshot({path:path.join(out,`before-${width}-${theme}.png`),fullPage:true})
        await page.close()
      }
    }
    const context = await browser.newContext({colorScheme:'dark',viewport:{width:1440,height:900}})
    const page = await context.newPage()
    await page.goto(base,{waitUntil:'networkidle'})
    assert.equal(await page.locator('html').getAttribute('data-theme'),'light','New visits default to light, even with a dark OS')
    const choose = async (value) => {
      await page.locator('.theme-picker > summary').click()
      await page.locator(`[data-theme-choice="${value}"]`).click()
      assert.equal(await page.locator(`[data-theme-choice="${value}"]`).getAttribute('aria-pressed'),'true')
    }
    await choose('dark')
    assert.equal(await page.locator('html').getAttribute('data-theme'),'dark')
    await page.reload({waitUntil:'networkidle'})
    assert.equal(await page.locator('html').getAttribute('data-theme'),'dark','Explicit choice persists')
    await choose('light')
    await page.reload({waitUntil:'networkidle'})
    assert.equal(await page.locator('html').getAttribute('data-theme'),'light')
    await choose('system')
    assert.equal(await page.locator('html').getAttribute('data-theme'),'dark')
    await page.emulateMedia({colorScheme:'light'})
    await page.waitForFunction(()=>document.documentElement.dataset.theme==='light')
    assert.equal(await page.locator('html').getAttribute('data-theme'),'light','System choice tracks OS changes')
    await page.locator('.theme-picker > summary').click()
    await page.keyboard.press('Escape')
    assert.equal(await page.locator('.theme-picker').getAttribute('open'),null)
    assert.equal(await page.evaluate(() => document.activeElement.matches('.theme-picker > summary')),true)
    await page.setViewportSize({width:390,height:900})
    const toggle=page.locator('#menu-toggle')
    assert.equal(await toggle.getAttribute('aria-expanded'),'false')
    assert.equal(await page.locator('.section-nav').isVisible(),false)
    await toggle.click()
    assert.equal(await page.locator('.section-nav').isVisible(),true)
    assert.equal(await toggle.getAttribute('aria-expanded'),'true')
    const targets=await page.locator('.section-nav a').evaluateAll(els=>els.map(el=>el.getAttribute('href')))
    assert.equal(targets.length,6)
    for (const href of targets) {
      if (await toggle.getAttribute('aria-expanded')==='false') await toggle.click()
      await page.locator(`.section-nav a[href="${href}"]`).click()
      assert.equal(await toggle.getAttribute('aria-expanded'),'false')
      const rect=await page.locator(href).boundingBox()
      assert.ok(rect.y>=-1 && rect.y<900,`Section visible after navigation: ${href}: ${rect.y}`)
    }
    await toggle.click()
    await page.keyboard.press('Escape')
    assert.equal(await toggle.getAttribute('aria-expanded'),'false')
    assert.equal(await page.evaluate(()=>document.activeElement.id),'menu-toggle')
    await toggle.click()
    await page.setViewportSize({width:1440,height:900})
    await page.waitForFunction(()=>document.querySelector('#menu-toggle').getAttribute('aria-expanded')==='false')
    assert.equal(await toggle.getAttribute('aria-expanded'),'false')
    assert.equal(await page.locator('.section-nav').isVisible(),true)
    await page.locator('.footer-ecosystem summary').click()
    const sizes=await page.locator('.footer-ecosystem a').evaluateAll(els=>els.map(el=>({href:el.href,width:el.getBoundingClientRect().width,height:el.getBoundingClientRect().height})))
    assert.ok(sizes.length>=3 && sizes.every(r=>r.width>=44 && r.height>=44))
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth-innerWidth),0)
    await context.close()
    const blocked=await browser.newContext({colorScheme:'dark'})
    await blocked.addInitScript(()=>Object.defineProperty(window,'localStorage',{get(){throw new DOMException('Blocked','SecurityError')}}))
    const p=await blocked.newPage()
    const errors=[];p.on('pageerror',e=>errors.push(e.message))
    await p.goto(base,{waitUntil:'networkidle'})
    assert.equal(await p.locator('html').getAttribute('data-theme'),'light')
    await p.locator('.theme-picker > summary').click()
    await p.locator('[data-theme-choice="dark"]').click()
    assert.equal(await p.locator('html').getAttribute('data-theme'),'dark','Theme works even when storage is blocked')
    assert.deepEqual(errors,[])
    await blocked.close()
    const nojs=await browser.newContext({javaScriptEnabled:false,viewport:{width:390,height:900}})
    const fallback=await nojs.newPage();await fallback.goto(base)
    assert.equal(await fallback.locator('.section-nav').isVisible(),true,'No-JS navigation remains reachable')
    assert.equal(await fallback.evaluate(()=>document.documentElement.scrollWidth-innerWidth),0)
    await nojs.close()
    const report={defaultLight:true,persistence:true,systemChanges:true,blockedStorage:true,mobileNavigation:true,escapeFocus:true,noJsNavigation:true,footerTargets:sizes}
    fs.writeFileSync(path.join(out,'shell-verification.json'),JSON.stringify(report,null,2)+'\n')
    console.log(JSON.stringify(report))
  } finally {await browser.close()}
})().catch(error=>{console.error(error);process.exitCode=1})
